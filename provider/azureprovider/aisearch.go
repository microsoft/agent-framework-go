// AISearchConfig configures Azure AI Search. Set exactly one of Credential and APIKey.
type AISearchConfig struct {
	Credential azcore.TokenCredential
	APIKey     *azcore.KeyCredential

	// Audience is the token audience. Empty uses https://search.azure.com.
	Audience string

	// ClientOptions configures the Azure HTTP pipeline. Default transports and
	// supplied *http.Client values reject cross-origin redirects. Other custom
	// transports are responsible for their own redirect handling.
	ClientOptions azcore.ClientOptions

	// EmbeddingGenerator supplies the default generator for collections.
	// Definition and property generators take precedence.
	EmbeddingGenerator *embedding.BoundGenerator
}

// AISearch manages Azure AI Search indexes through its embedded [vectordata.Store].
// Create it with [NewAISearch]. Pass the embedded field to provider-independent
// APIs. Methods support concurrent use.
//
// Keys are strings or uuid.UUID values. UUID keys are generated by default.
// Data fields support strings, booleans, signed integers, float32, float64,
// time.Time, nullable pointers to these types, and slices or arrays of scalars.
// Native vectors are []float32, embedding.VectorOf[float32], embedding.Of[float32],
// and *embedding.Of[float32]. Non-native vector fields require an embedding
// generator for upserts. String search inputs without a configured generator
// are sent to the index's server-side vectorizer.
//
// Property storage names, including vectordata storage tags, define index field
// names. Record-level json tags do not override them. Only schema properties are
// uploaded. Nil collection fields are uploaded as empty arrays; nullable scalar
// fields remain null. Retrieval creates independent records and excludes vectors
// by default. IncludeVectors is unsupported for generated vector fields.
//
// AISearch and its collections borrow credentials, generators, and transports
// and need no Close. Upserts and batch deletions can partially succeed; errors
// report failed documents. Generated keys are written to pointer and map inputs
// before upload. Plain structs are copied by value. Callers must not concurrently
// mutate inputs.
type AISearch struct {
	*vectordata.Store
}

type store struct {
	client    *serviceClient
	generator *embedding.BoundGenerator
}

// NewAISearch creates a store for an Azure AI Search service endpoint, such as
// https://example.search.windows.net. It uses the 2025-09-01 REST API and the
// Azure SDK HTTP pipeline. Construction does not contact the service.
// Retry, logging, and transport settings use config.ClientOptions.
func NewAISearch(endpoint string, config AISearchConfig) (*AISearch, error) {
	client, err := newServiceClient(endpoint, config)
	if err != nil {
		return nil, err
	}
	provider := &store{client: client, generator: config.EmbeddingGenerator}
	return &AISearch{Store: vectordata.NewStore(provider)}, nil
}

func (s *store) OpenCollection(name string, keyType, recordType reflect.Type, definition *vectordata.Definition) (vectordata.Collection[any, any], error) {
	return newCollection(s, name, keyType, recordType, definition)
}

func (s *store) ListCollectionNames(ctx context.Context) iter.Seq2[string, error] {
	return func(yield func(string, error) bool) {
		endpoint := s.client.url("/indexes", url.Values{"$select": {"name"}})
		for {
			var page struct {
				Value []struct {
					Name string `json:"name"`
				} `json:"value"`
				NextLink string `json:"@odata.nextLink"`
			}
			if err := s.client.request(ctx, http.MethodGet, endpoint, nil, &page, http.StatusOK); err != nil {
				yield("", failure("", "GetIndexNames", err))
				return
			}
			if page.Value == nil {
				yield("", failure("", "GetIndexNames", errors.New("response is missing index names")))
				return
			}
			for _, index := range page.Value {
				if err := ctx.Err(); err != nil {
					yield("", failure("", "GetIndexNames", err))
					return
				}
				if index.Name == "" {
					yield("", failure("", "GetIndexNames", errors.New("response contains an index without a name")))
					return
				}
				if !yield(index.Name, nil) {
					return
				}
			}
			if page.NextLink == "" {
				return
			}
			var err error
			endpoint, err = s.client.nextURL(endpoint, page.NextLink)
			if err != nil {
				yield("", failure("", "GetIndexNames", err))
				return
			}
		}
	}
}

func (s *store) CollectionExists(ctx context.Context, name string) (bool, error) {
	if strings.TrimSpace(name) == "" {
		return false, failure(name, "GetIndex", errors.New("collection name is required"))
	}
	var index json.RawMessage
	err := s.client.request(ctx, http.MethodGet, s.client.url(indexPath(name), nil), nil, &index, http.StatusOK)
	if isStatus(err, http.StatusNotFound) {
		return false, nil
	}
	if err != nil {
		return false, failure(name, "GetIndex", err)
	}
	return true, nil
}

func (s *store) EnsureCollectionDeleted(ctx context.Context, name string) error {
	if strings.TrimSpace(name) == "" {
		return failure(name, "DeleteIndex", errors.New("collection name is required"))
	}
	err := s.client.request(ctx, http.MethodDelete, s.client.url(indexPath(name), nil), nil, nil, http.StatusNoContent)
	if err != nil && !isStatus(err, http.StatusNotFound) {
		return failure(name, "DeleteIndex", err)
	}
	return nil
}

func indexPath(name string) string {
	return "/indexes('" + url.PathEscape(strings.ReplaceAll(name, "'", "''")) + "')"
}

func isStatus(err error, status int) bool {
	responseErr, ok := errors.AsType[*azcore.ResponseError](err)
	return ok && responseErr.StatusCode == status
}

func failure(name, operation string, err error) error {
	return &vectordata.Error{
		SystemName: "azure.aisearch", CollectionName: name, OperationName: operation, Err: err,
	}
}

var _ vectordata.StoreProvider = (*store)(nil)
