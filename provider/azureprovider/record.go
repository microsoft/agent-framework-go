func keyString(key any) (string, error) {
	if key == nil {
		return "", fmt.Errorf("key is required")
	}
	if value, ok := key.(uuid.UUID); ok {
		return value.String(), nil
	}
	value := reflect.ValueOf(key)
	if value.Kind() != reflect.String {
		return "", fmt.Errorf("key must be a string or uuid.UUID, got %T", key)
	}
	if strings.TrimSpace(value.String()) == "" {
		return "", fmt.Errorf("key must not be blank")
	}
	return value.String(), nil
}

func (c *collection) prepareRecord(record any) (any, error) {
	value := reflect.ValueOf(record)
	if !value.IsValid() || !value.Type().AssignableTo(c.recordType) {
		return nil, fmt.Errorf("record must have type %v, got %T", c.recordType, record)
	}
	if value.Type() != c.recordType {
		assigned := reflect.New(c.recordType).Elem()
		assigned.Set(value)
		value = assigned
	}
	if value.Kind() == reflect.Struct {
		owned := reflect.New(c.recordType)
		owned.Elem().Set(value)
		return owned.Interface(), nil
	}
	if value.IsNil() || value.Kind() == reflect.Pointer && value.Elem().Kind() == reflect.Map && value.Elem().IsNil() {
		return nil, fmt.Errorf("record must not be nil")
	}
	return value.Interface(), nil
}

func (c *collection) encodeRecord(record any, index int, generated map[string][][]float32) (map[string]any, error) {
	key, found, err := c.key.Value(record)
	if err != nil {
		return nil, err
	}
	if c.key.IsAutoGenerated && (!found || key == nil || key == uuid.Nil) {
		key, err = uuid.NewRandom()
		if err != nil {
			return nil, err
		}
		if err := c.key.SetValue(record, key); err != nil {
			return nil, err
		}
	}
	stringKey, err := keyString(key)
	if err != nil {
		return nil, fmt.Errorf("property %q: %w", c.key.Name, err)
	}
	document := make(map[string]any, len(c.model.Properties)+1)
	document[c.key.StorageName] = stringKey
	for _, property := range c.data {
		value, found, err := property.Value(record)
		if err != nil {
			return nil, err
		}
		if !found {
			continue
		}
		typ := property.Type
		if typ.Kind() == reflect.Pointer {
			typ = typ.Elem()
		}
		if typ.Kind() == reflect.Slice || typ.Kind() == reflect.Array {
			reflected := reflect.ValueOf(value)
			if reflected.IsValid() && reflected.Kind() == reflect.Pointer {
				reflected = reflected.Elem()
			}
			// Azure collection fields cannot be null.
			if !reflected.IsValid() || reflected.Kind() == reflect.Slice && reflected.IsNil() {
				value = []any{}
			}
		}
		document[property.StorageName] = value
	}
	for _, property := range c.vectors {
		value, found, err := property.Value(record)
		if err != nil {
			return nil, err
		}
		if !found {
			continue
		}
		if outputs, wasGenerated := generated[property.Name]; wasGenerated {
			document[property.StorageName] = outputs[index]
			continue
		}
		vector, ok := providerservices.AsVector[float32](value)
		if !ok && value != nil {
			return nil, fmt.Errorf("property %q requires a float32 vector", property.Name)
		}
		if vector == nil {
			vector = []float32{}
		}
		document[property.StorageName] = vector
	}
	return document, nil
}

func (c *collection) decodeRecord(document map[string]json.RawMessage, includeVectors bool) (any, error) {
	root := reflect.New(c.recordType)
	target := root.Interface()
	recordType := c.recordType
	if recordType.Kind() == reflect.Pointer {
		recordType = recordType.Elem()
		root.Elem().Set(reflect.New(recordType))
		target = root.Elem().Interface()
	}
	if recordType.Kind() == reflect.Map {
		value := reflect.ValueOf(target).Elem()
		value.Set(reflect.MakeMap(recordType))
	}
	key, ok := document[c.key.StorageName]
	if !ok || bytes.Equal(bytes.TrimSpace(key), []byte("null")) {
		return nil, fmt.Errorf("response is missing key property %q", c.key.StorageName)
	}
	var stringKey string
	if err := json.Unmarshal(key, &stringKey); err != nil {
		return nil, fmt.Errorf("property %q: %w", c.key.Name, err)
	}
	if _, err := keyString(stringKey); err != nil {
		return nil, fmt.Errorf("property %q: %w", c.key.Name, err)
	}
	keyValue := reflect.New(c.key.Type)
	if err := json.Unmarshal(key, keyValue.Interface()); err != nil {
		return nil, fmt.Errorf("property %q: %w", c.key.Name, err)
	}
	if err := c.key.SetValue(target, keyValue.Elem().Interface()); err != nil {
		return nil, err
	}
	for _, property := range c.data {
		raw, found := document[property.StorageName]
		if !found {
			continue
		}
		value, err := decodeValue(raw, property.Type)
		if err != nil {
			return nil, fmt.Errorf("property %q: %w", property.Name, err)
		}
		if err := property.SetValue(target, value); err != nil {
			return nil, err
		}
	}
	if includeVectors {
		for _, property := range c.vectors {
			raw, found := document[property.StorageName]
			if !found {
				continue
			}
			value, err := decodeVector(raw, property)
			if err != nil {
				return nil, fmt.Errorf("property %q: %w", property.Name, err)
			}
			if err := property.SetValue(target, value); err != nil {
				return nil, err
			}
		}
	}
	return root.Elem().Interface(), nil
}

func decodeValue(raw json.RawMessage, typ reflect.Type) (any, error) {
	if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) {
		return nil, nil
	}
	value := reflect.New(typ)
	if err := json.Unmarshal(raw, value.Interface()); err != nil {
		return nil, err
	}
	return value.Elem().Interface(), nil
}

func decodeVector(raw json.RawMessage, property *providerservices.VectorPropertyModel) (any, error) {
	if property.Type == reflect.TypeFor[embedding.Of[float32]]() || property.Type == reflect.TypeFor[*embedding.Of[float32]]() {
		if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) {
			return nil, nil
		}
		var vector embedding.VectorOf[float32]
		if err := json.Unmarshal(raw, &vector); err != nil {
			return nil, err
		}
		result := embedding.Of[float32]{Vector: vector}
		if property.Type.Kind() == reflect.Pointer {
			return &result, nil
		}
		return result, nil
	}
	return decodeValue(raw, property.Type)
}
