package inmemory

import (
	"fmt"
	"reflect"

	"github.com/microsoft/agent-framework-go/vectordata"
	"github.com/microsoft/agent-framework-go/vectordata/internal/recordvalue"
	"github.com/microsoft/agent-framework-go/vectordata/providerservices"
)

type recordField struct {
	name     string
	typ      reflect.Type
	index    []int
	property providerservices.PropertyModel
	vector   *providerservices.VectorPropertyModel
}

type recordSchema struct {
	typ              reflect.Type
	fields           map[string]recordField
	key              recordField
	keyAutoGenerated bool
	vectors          []recordField
}

func newRecordSchema(typ reflect.Type, model *providerservices.CollectionModel) recordSchema {
	if typ.Kind() == reflect.Pointer {
		typ = typ.Elem()
	}
	schema := recordSchema{typ: typ, fields: make(map[string]recordField)}
	for _, property := range model.Properties {
		var field recordField
		switch p := property.(type) {
		case *providerservices.KeyPropertyModel:
			field = recordField{name: p.Name, typ: p.Type}
			schema.keyAutoGenerated = p.IsAutoGenerated
		case *providerservices.DataPropertyModel:
			field = recordField{name: p.Name, typ: p.Type}
		case *providerservices.VectorPropertyModel:
			field = recordField{name: p.Name, typ: p.Type, vector: p}
		}
		field.property = property
		schema.fields[field.name] = field
		if _, ok := property.(*providerservices.KeyPropertyModel); ok {
			schema.key = field
		}
		if field.vector != nil {
			schema.vectors = append(schema.vectors, field)
		}
	}
	if typ.Kind() == reflect.Struct {
		for _, field := range reflect.VisibleFields(typ) {
			if _, mapped := schema.fields[field.Name]; !mapped && field.IsExported() {
				schema.fields[field.Name] = recordField{name: field.Name, typ: field.Type, index: field.Index}
			}
		}
	}
	return schema
}

func (s recordSchema) compileFilter(filter *vectordata.Filter) (func(any) (bool, error), error) {
	return providerservices.CompileFilter(filter, func(name string) (providerservices.FilterProperty, error) {
		field, found := s.fields[name]
		if !found {
			return providerservices.FilterProperty{}, fmt.Errorf("filter property %q was not found", name)
		}
		return field.localProperty(), nil
	})
}

func (f recordField) localProperty() providerservices.FilterProperty {
	property := providerservices.FilterProperty{Type: f.typ}
	if f.property != nil {
		property.Value = f.property.Value
	} else {
		property.Value = func(record any) (any, bool, error) {
			value, found, err := f.read(reflect.ValueOf(record))
			if err != nil || !value.IsValid() {
				return nil, found, err
			}
			return value.Interface(), found, nil
		}
	}
	return property
}

func (f recordField) read(record reflect.Value) (reflect.Value, bool, error) {
	if f.property != nil {
		value, found, err := f.property.Value(record.Interface())
		return reflect.ValueOf(value), found, err
	}
	if record.Kind() == reflect.Pointer {
		record = record.Elem()
	}
	value, err := record.FieldByIndexErr(f.index)
	if err != nil {
		return reflect.Value{}, false, nil
	}
	return value, true, nil
}

func (s recordSchema) validateRecord(record reflect.Value) error {
	root := record
	if root.Kind() == reflect.Pointer {
		root = root.Elem()
	}
	if !root.IsValid() || root.Kind() == reflect.Map && root.IsNil() {
		return fmt.Errorf("record must not be nil")
	}
	for _, field := range s.fields {
		value, found, err := field.read(record)
		if err != nil {
			return err
		}
		if field.vector == nil || field.vector.Type != field.vector.EmbeddingType || !found || !value.IsValid() {
			continue
		}
		vector, ok := providerservices.AsVector[float32](value.Interface())
		if !ok {
			return fmt.Errorf("property %q is not a supported vector", field.name)
		}
		if vector != nil {
			if err := validateVector(vector, field.vector.Dimensions); err != nil {
				return fmt.Errorf("property %q: %w", field.name, err)
			}
		}
	}
	return nil
}

func recordKey(field recordField, record reflect.Value, keyType reflect.Type) (any, error) {
	value, found, err := field.read(record)
	if err != nil {
		return nil, err
	}
	if !found {
		return nil, fmt.Errorf("key property %q is missing", field.name)
	}
	if err := validateKey(value); err != nil {
		return nil, fmt.Errorf("key property %q: %w", field.name, err)
	}
	key := reflect.New(keyType).Elem()
	if !value.Type().AssignableTo(key.Type()) {
		// Assignability through the declared property type is not transitive.
		declared := reflect.New(field.typ).Elem()
		declared.Set(value)
		value = declared
	}
	key.Set(value)
	return key.Interface(), nil
}

func collectionRecord[R any](record any) (R, error) {
	if typed, ok := record.(R); ok {
		return typed, nil
	}
	var zero R
	return zero, fmt.Errorf("stored record has type %T, want %v", record, reflect.TypeFor[R]())
}

func validateKey(value reflect.Value) error {
	for value.IsValid() && value.Kind() == reflect.Interface {
		value = value.Elem()
	}
	if recordvalue.IsNil(value) || !value.Comparable() {
		return fmt.Errorf("key must be a non-nil comparable value")
	}
	if !value.Equal(value) {
		return fmt.Errorf("key must not contain NaN")
	}
	return nil
}
