// Package providerservices provides experimental model-building, record-access,
// vector-conversion, embedding-batching, and local filtering and sorting support
// for vector data providers, not applications. Providers build a model when
// creating a collection handle and retain it for subsequent operations. Local
// filtering and sorting are optional; remote providers translate them to their
// backend queries.
//
// This package does not implement a database connector, record serialization,
// or vector storage. Its API may change independently of the core vector
// data contracts.
package providerservices

import (
	"fmt"
	"maps"
	"reflect"
	"strconv"
	"strings"

	"github.com/microsoft/agent-framework-go/embedding"
	"github.com/microsoft/agent-framework-go/vectordata"
)

// Config describes a provider's model-building policies. SupportsDataType and
// SupportsVectorType are required. Type predicates are called synchronously
// during [Build] and are not retained by the model.
type Config struct {
	// SupportsMultipleVectors permits more than one vector property.
	SupportsMultipleVectors bool
	// RequiresAtLeastOneVector rejects records with no vector properties.
	RequiresAtLeastOneVector bool
	// ReservedKeyStorageName overrides key storage names when nonempty.
	ReservedKeyStorageName string
	// SupportsKeyType optionally restricts supported key property types.
	SupportsKeyType func(reflect.Type) bool
	// SupportsDataType identifies supported stored data types.
	SupportsDataType func(reflect.Type) bool
	// SupportsVectorType identifies supported native vectors and embedding
	// outputs. A type is not considered native merely because it is a slice
	// or implements embedding.Vector.
	SupportsVectorType func(reflect.Type) bool
	// SupportsKeyAutoGeneration controls both support and the default when
	// IsAutoGenerated is unset. Nil means auto-generation is unsupported.
	SupportsKeyAutoGeneration func(reflect.Type) bool
	// DefaultEmbeddingGenerator supplies the fallback when the definition has
	// no generator. Property and definition generators take precedence.
	// The generator is borrowed, not closed by the model.
	DefaultEmbeddingGenerator *embedding.BoundGenerator
}

// Build resolves runtime key and record types into a provider-owned model.
// Both types must be non-nil. recordType must be a struct, map[string]any, or a
// pointer to either. Dynamic records require a definition with explicit property
// types. A nil definition uses the record's vectordata tags.
//
// Untagged fields are ignored unless included in Definition; "-" suppresses tag
// inference. Explicit properties must have the same role as their tags. Definition
// values override tag settings, while empty storage, index, and distance names
// retain tag settings. A definition's nil IsAutoGenerated restores provider defaults.
//
// The result owns its property models and annotation maps. Annotation values
// and embedding generators are shared. Inputs are read-only. Exactly one key is
// required and its type must be assignable to keyType.
// Property accessors are configured once for the resolved record type. They
// read and assign values without cloning records or applying provider policies.
//
// Native vector fields retain their record type as their embedding type. Other
// fields must match a generator's concrete input type or implement its input
// interface, and the generator's output must be supported by the provider.
// Generators are resolved from the property, then the definition, then
// config.DefaultEmbeddingGenerator.
// Without a generator, a non-native field requires an explicit supported
// embedding type for provider-managed generation.
//
// Build does not invoke generators or create database collections. Providers
// remain responsible for validating index choices, distance functions, and
// representation-specific storage requirements.
func Build(keyType, recordType reflect.Type, definition *vectordata.Definition, config Config) (*CollectionModel, error) {
	if keyType == nil || recordType == nil {
		return nil, fmt.Errorf("vectordata: key and record types are required")
	}
	if config.SupportsDataType == nil || config.SupportsVectorType == nil {
		return nil, fmt.Errorf("vectordata: provider must specify supported data and vector types")
	}
	if recordType.Kind() == reflect.Pointer {
		recordType = recordType.Elem()
	}
	dynamic := recordType.Kind() == reflect.Map &&
		recordType.Key() == reflect.TypeFor[string]() && recordType.Elem() == reflect.TypeFor[any]()
	if recordType.Kind() != reflect.Struct && !dynamic {
		return nil, fmt.Errorf("vectordata: record type %v must be a struct or map[string]any", recordType)
	}
	if dynamic && definition == nil {
		return nil, fmt.Errorf("vectordata: dynamic records require a definition")
	}
	result := &CollectionModel{}
	generator := config.DefaultEmbeddingGenerator
	definitions := make(map[string]PropertyModel)
	if definition != nil {
		if definition.EmbeddingGenerator != nil {
			generator = definition.EmbeddingGenerator
		}
		for _, property := range definition.Properties {
			clone, err := newPropertyModel(property)
			if err != nil {
				return nil, err
			}
			name := clone.propertyInfo().name
			if strings.TrimSpace(name) == "" {
				return nil, fmt.Errorf("vectordata: property name is required")
			}
			if _, exists := definitions[name]; exists {
				return nil, fmt.Errorf("vectordata: duplicate property %q", name)
			}
			definitions[name] = clone
			if dynamic {
				result.Properties = append(result.Properties, clone)
			}
		}
	}
	if generator != nil {
		if err := validateEmbeddingGenerator(generator); err != nil {
			return nil, err
		}
	}
	if !dynamic {
		for _, field := range reflect.VisibleFields(recordType) {
			tag, tagged := field.Tag.Lookup("vectordata")
			if field.PkgPath != "" {
				if tagged && tag != "-" {
					return nil, fmt.Errorf("vectordata: property %q must be exported", field.Name)
				}
				continue
			}
			var property PropertyModel
			if tagged && tag != "-" {
				var err error
				property, err = parsePropertyTag(field, tag)
				if err != nil {
					return nil, err
				}
			}
			if explicit, ok := definitions[field.Name]; ok {
				if property != nil {
					var err error
					explicit, err = mergeProperty(property, explicit)
					if err != nil {
						return nil, err
					}
				}
				property = explicit
				delete(definitions, field.Name)
			}
			if property == nil {
				continue
			}
			if err := resolveProperty(property, field.Type, generator, config); err != nil {
				return nil, err
			}
			property.configureAccessor(recordType, property.propertyInfo(), field.Index)
			result.Properties = append(result.Properties, property)
		}
		if len(definitions) != 0 {
			for name := range definitions {
				return nil, fmt.Errorf("vectordata: property %q is not an exported field of %v", name, recordType)
			}
		}
	} else {
		for _, property := range result.Properties {
			if err := resolveProperty(property, nil, generator, config); err != nil {
				return nil, err
			}
			property.configureAccessor(recordType, property.propertyInfo(), nil)
		}
	}
	storageNames := make(map[string]string)
	keys := 0
	vectors := 0
	for _, property := range result.Properties {
		info := property.propertyInfo()
		if previous, exists := storageNames[info.storageName]; exists {
			return nil, fmt.Errorf("vectordata: properties %q and %q share storage name %q", previous, info.name, info.storageName)
		}
		storageNames[info.storageName] = info.name
		if _, ok := property.(*KeyPropertyModel); ok {
			keys++
			if !info.typ.AssignableTo(keyType) {
				return nil, fmt.Errorf("vectordata: key property %q has type %v, not assignable to %v", info.name, info.typ, keyType)
			}
		}
		if p, ok := property.(*VectorPropertyModel); ok {
			vectors++
			result.EmbeddingGenerationRequired = result.EmbeddingGenerationRequired || p.EmbeddingType != p.Type
		}
	}
	if keys != 1 {
		return nil, fmt.Errorf("vectordata: expected one key property, got %d", keys)
	}
	if config.RequiresAtLeastOneVector && vectors == 0 {
		return nil, fmt.Errorf("vectordata: provider requires at least one vector property")
	}
	if !config.SupportsMultipleVectors && vectors > 1 {
		return nil, fmt.Errorf("vectordata: provider does not support multiple vector properties")
	}
	return result, nil
}

func newPropertyModel(property vectordata.Property) (PropertyModel, error) {
	switch p := property.(type) {
	case *vectordata.KeyProperty:
		if p != nil {
			return &KeyPropertyModel{
				Name: p.Name, Type: p.Type, StorageName: p.StorageName,
				ProviderAnnotations: maps.Clone(p.ProviderAnnotations),
				autoGenerated:       p.IsAutoGenerated,
			}, nil
		}
	case *vectordata.DataProperty:
		if p != nil {
			return &DataPropertyModel{
				Name: p.Name, Type: p.Type, StorageName: p.StorageName,
				ProviderAnnotations: maps.Clone(p.ProviderAnnotations),
				IsIndexed:           p.IsIndexed, IsFullTextIndexed: p.IsFullTextIndexed,
			}, nil
		}
	case *vectordata.VectorProperty:
		if p != nil {
			return &VectorPropertyModel{
				Name: p.Name, Type: p.Type, StorageName: p.StorageName,
				ProviderAnnotations: maps.Clone(p.ProviderAnnotations),
				Dimensions:          p.Dimensions, IndexKind: p.IndexKind, DistanceFunction: p.DistanceFunction,
				EmbeddingGenerator: p.EmbeddingGenerator, EmbeddingType: p.EmbeddingType,
			}, nil
		}
	}
	return nil, fmt.Errorf("vectordata: property definition must be non-nil")
}

func mergeProperty(tag, explicit PropertyModel) (PropertyModel, error) {
	if reflect.TypeOf(tag) != reflect.TypeOf(explicit) {
		return nil, fmt.Errorf("vectordata: property %q has conflicting tag and definition roles", explicit.propertyInfo().name)
	}
	switch p := explicit.(type) {
	case *KeyPropertyModel:
		if p.StorageName == "" {
			p.StorageName = tag.propertyInfo().storageName
		}
	case *DataPropertyModel:
		if p.StorageName == "" {
			p.StorageName = tag.propertyInfo().storageName
		}
	case *VectorPropertyModel:
		original := tag.(*VectorPropertyModel)
		if p.StorageName == "" {
			p.StorageName = original.StorageName
		}
		if p.IndexKind == "" {
			p.IndexKind = original.IndexKind
		}
		if p.DistanceFunction == "" {
			p.DistanceFunction = original.DistanceFunction
		}
	}
	return explicit, nil
}

func resolveProperty(property PropertyModel, fieldType reflect.Type, generator *embedding.BoundGenerator, config Config) error {
	info := property.propertyInfo()
	if info.typ == nil {
		info.typ = fieldType
	} else if fieldType != nil && info.typ != fieldType {
		return fmt.Errorf("vectordata: property %q has type %v in the definition and %v on the record", info.name, info.typ, fieldType)
	}
	if info.typ == nil {
		return fmt.Errorf("vectordata: property %q requires a type", info.name)
	}
	if info.storageName == "" {
		info.storageName = info.name
	}
	switch p := property.(type) {
	case *KeyPropertyModel:
		p.Type, p.StorageName = info.typ, info.storageName
		if config.ReservedKeyStorageName != "" {
			p.StorageName = config.ReservedKeyStorageName
		}
		if config.SupportsKeyType != nil && !config.SupportsKeyType(p.Type) {
			return fmt.Errorf("vectordata: key property %q has unsupported type %v", p.Name, p.Type)
		}
		supportsAutoGeneration := config.SupportsKeyAutoGeneration != nil && config.SupportsKeyAutoGeneration(p.Type)
		p.IsAutoGenerated = supportsAutoGeneration
		if p.autoGenerated != nil {
			p.IsAutoGenerated = *p.autoGenerated
			p.autoGenerated = nil
		}
		if p.IsAutoGenerated && !supportsAutoGeneration {
			return fmt.Errorf("vectordata: key property %q does not support auto-generation for type %v", p.Name, p.Type)
		}
	case *DataPropertyModel:
		p.Type, p.StorageName = info.typ, info.storageName
		if !config.SupportsDataType(p.Type) {
			return fmt.Errorf("vectordata: data property %q has unsupported type %v", p.Name, p.Type)
		}
	case *VectorPropertyModel:
		if p.Dimensions <= 0 {
			return fmt.Errorf("vectordata: vector property %q requires positive dimensions", info.name)
		}
		if err := validateBuiltinName(info.name, "index", p.IndexKind,
			vectordata.HNSW, vectordata.Flat, vectordata.IVFFlat, vectordata.DiskANN, vectordata.QuantizedFlat, vectordata.Dynamic,
		); err != nil {
			return err
		}
		if err := validateBuiltinName(info.name, "distance", p.DistanceFunction,
			vectordata.CosineSimilarity, vectordata.CosineDistance, vectordata.DotProductSimilarity, vectordata.NegativeDotProductSimilarity,
			vectordata.EuclideanDistance, vectordata.EuclideanSquaredDistance, vectordata.HammingDistance, vectordata.ManhattanDistance,
		); err != nil {
			return err
		}
		p.Type, p.StorageName = info.typ, info.storageName
		if p.EmbeddingGenerator == nil {
			p.EmbeddingGenerator = generator
		}
		binding := p.EmbeddingGenerator
		if binding != nil {
			if err := validateEmbeddingGenerator(binding); err != nil {
				return fmt.Errorf("vectordata: vector property %q: %w", info.name, err)
			}
		}
		if config.SupportsVectorType(p.Type) {
			if p.EmbeddingType != nil && p.EmbeddingType != p.Type {
				return fmt.Errorf("vectordata: native vector property %q must use its record type %v as its embedding type, not %v", p.Name, p.Type, p.EmbeddingType)
			}
			p.EmbeddingType = p.Type
		} else if binding != nil {
			inputType := binding.InputType()
			compatibleInput := p.Type == inputType || inputType.Kind() == reflect.Interface && p.Type.AssignableTo(inputType)
			if !compatibleInput {
				return fmt.Errorf("vectordata: vector property %q has type %v, but its embedding generator accepts %v", info.name, p.Type, inputType)
			}
			if p.EmbeddingType != nil && p.EmbeddingType != binding.EmbeddingType() {
				return fmt.Errorf("vectordata: vector property %q requests embedding type %v, but its generator produces %v", info.name, p.EmbeddingType, binding.EmbeddingType())
			}
			p.EmbeddingType = binding.EmbeddingType()
		}
		if p.EmbeddingType == nil {
			return fmt.Errorf("vectordata: vector property %q has unsupported type %v and no embedding generator or explicit embedding type", p.Name, p.Type)
		}
		if !config.SupportsVectorType(p.EmbeddingType) {
			return fmt.Errorf("vectordata: vector property %q has unsupported embedding type %v", p.Name, p.EmbeddingType)
		}
		if binding != nil && config.SupportsVectorType(binding.EmbeddingType()) {
			p.SearchEmbeddingGenerator = binding
		}
	}
	return nil
}

func validateBuiltinName[T ~string](property, setting string, value T, builtins ...T) error {
	lower := strings.ToLower(string(value))
	for _, canonical := range builtins {
		if value != canonical && (lower == string(canonical) || lower == strings.ReplaceAll(string(canonical), "_", "")) {
			return fmt.Errorf("vectordata: property %q %s %q must use %q", property, setting, value, canonical)
		}
	}
	return nil
}

func validateEmbeddingGenerator(generator *embedding.BoundGenerator) error {
	if generator.InputType() == nil || generator.EmbeddingType() == nil {
		return fmt.Errorf("vectordata: embedding generator must be created with embedding.Bind")
	}
	return nil
}

func parsePropertyTag(field reflect.StructField, tag string) (PropertyModel, error) {
	parts := strings.Split(tag, ",")
	var property PropertyModel
	switch parts[0] {
	case "key":
		property = &KeyPropertyModel{Name: field.Name, Type: field.Type}
	case "data":
		property = &DataPropertyModel{Name: field.Name, Type: field.Type}
	case "vector":
		property = &VectorPropertyModel{Name: field.Name, Type: field.Type}
	default:
		return nil, fmt.Errorf("vectordata: invalid role %q on property %q", parts[0], field.Name)
	}
	seen := make(map[string]bool)
	for _, part := range parts[1:] {
		key, value, hasValue := strings.Cut(part, "=")
		if seen[key] {
			return nil, fmt.Errorf("vectordata: duplicate tag setting %q on property %q", key, field.Name)
		}
		seen[key] = true
		if key == "storage" && hasValue && value != "" {
			switch p := property.(type) {
			case *KeyPropertyModel:
				p.StorageName = value
			case *DataPropertyModel:
				p.StorageName = value
			case *VectorPropertyModel:
				p.StorageName = value
			}
			continue
		}
		if key == "autogenerated" || key == "indexed" || key == "fulltext" {
			enabled := true
			if hasValue {
				var err error
				enabled, err = strconv.ParseBool(value)
				if err != nil {
					return nil, fmt.Errorf("vectordata: invalid %s on property %q: %w", key, field.Name, err)
				}
			}
			switch p := property.(type) {
			case *KeyPropertyModel:
				if key == "autogenerated" {
					p.autoGenerated = new(enabled)
					continue
				}
			case *DataPropertyModel:
				if key == "indexed" {
					p.IsIndexed = enabled
					continue
				}
				if key == "fulltext" {
					p.IsFullTextIndexed = enabled
					continue
				}
			}
		}
		if p, ok := property.(*VectorPropertyModel); ok && hasValue {
			switch key {
			case "dimensions":
				dimensions, err := strconv.Atoi(value)
				if err != nil || dimensions <= 0 {
					return nil, fmt.Errorf("vectordata: property %q requires positive integer dimensions", field.Name)
				}
				p.Dimensions = dimensions
				continue
			case "index":
				p.IndexKind = vectordata.IndexKind(value)
				continue
			case "distance":
				p.DistanceFunction = vectordata.DistanceFunction(value)
				continue
			}
		}
		return nil, fmt.Errorf("vectordata: invalid tag setting %q on property %q", part, field.Name)
	}
	return property, nil
}
