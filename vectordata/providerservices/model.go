package providerservices

import (
	"fmt"
	"reflect"

	"github.com/microsoft/agent-framework-go/embedding"
	"github.com/microsoft/agent-framework-go/vectordata"
)

// CollectionModel contains a provider's resolved collection schema. Create it
// with [Build] and treat it as read-only when sharing it between operations.
// Properties are ordered by struct field order, or definition order for dynamic
// records. Annotation maps belong to the model; their values and generators are
// shared with the caller.
type CollectionModel struct {
	Properties []PropertyModel
	// EmbeddingGenerationRequired reports whether any record field needs
	// conversion to its resolved embedding type. Conversion may be performed
	// by a configured generator or by the provider.
	EmbeddingGenerationRequired bool
}

// PropertyModel describes a resolved key, data, or vector property. Its
// implementations are *KeyPropertyModel, *DataPropertyModel, and
// *VectorPropertyModel. [Build] configures their record accessors.
type PropertyModel interface {
	// Value reads the property using ordinary Go value semantics; reference-valued
	// contents are shared. It accepts the struct or map type used by [Build], or
	// a pointer to it. A missing dynamic entry or nil embedded pointer returns
	// found=false; a present nil value returns found=true. Invalid records and
	// incompatible dynamic values return errors.
	Value(record any) (value any, found bool, err error)

	// SetValue assigns a value using Go's assignment rules without cloning
	// reference-valued contents. Struct records must be passed by pointer;
	// maps may be passed directly or by pointer.
	// Nil embedded pointers are initialized when their fields are writable.
	// A nil value clears a nil-capable struct field or stores nil in a dynamic
	// map entry; it does not remove the entry. Invalid assignments return errors.
	SetValue(record, value any) error

	propertyInfo() propertyInfo
	configureAccessor(recordType reflect.Type, info propertyInfo, index []int)
}

// KeyPropertyModel contains the effective key configuration. IsAutoGenerated is
// resolved from the explicit setting or the provider's support for the key type.
type KeyPropertyModel struct {
	propertyAccessor

	Name                string
	Type                reflect.Type
	StorageName         string
	ProviderAnnotations map[string]any
	IsAutoGenerated     bool

	autoGenerated *bool
}

// DataPropertyModel contains the effective configuration of a stored data field.
type DataPropertyModel struct {
	propertyAccessor

	Name                string
	Type                reflect.Type
	StorageName         string
	ProviderAnnotations map[string]any
	IsIndexed           bool
	IsFullTextIndexed   bool
}

// VectorPropertyModel contains a vector property's effective configuration.
// EmbeddingType equals Type for native vector fields, and otherwise identifies
// the supported output of embedding generation.
type VectorPropertyModel struct {
	propertyAccessor

	Name                string
	Type                reflect.Type
	StorageName         string
	ProviderAnnotations map[string]any
	Dimensions          int
	IndexKind           vectordata.IndexKind
	DistanceFunction    vectordata.DistanceFunction
	EmbeddingType       reflect.Type
	EmbeddingGenerator  *embedding.BoundGenerator
	// SearchEmbeddingGenerator is the configured generator when its output
	// type is supported by the provider. Otherwise it is nil; native vector
	// records remain valid, but unsupported search inputs must be rejected.
	// Query input compatibility is checked by the binding at generation time.
	SearchEmbeddingGenerator *embedding.BoundGenerator
}

type propertyInfo struct {
	name        string
	storageName string
	typ         reflect.Type
}

func (p *KeyPropertyModel) propertyInfo() propertyInfo {
	return propertyInfo{p.Name, p.StorageName, p.Type}
}

func (p *DataPropertyModel) propertyInfo() propertyInfo {
	return propertyInfo{p.Name, p.StorageName, p.Type}
}

func (p *VectorPropertyModel) propertyInfo() propertyInfo {
	return propertyInfo{p.Name, p.StorageName, p.Type}
}

// VectorProperty selects a vector property by record name. An empty name is
// valid only when exactly one vector property exists. The returned property
// belongs to the model and must be treated as read-only.
func (m *CollectionModel) VectorProperty(name string) (*VectorPropertyModel, error) {
	var selected *VectorPropertyModel
	if m != nil {
		for _, property := range m.Properties {
			if p, ok := property.(*VectorPropertyModel); ok && p != nil && (name == "" || p.Name == name) {
				if selected != nil {
					return nil, fmt.Errorf("vectordata: vector property selection is ambiguous")
				}
				selected = p
			}
		}
	}
	if selected == nil {
		return nil, fmt.Errorf("vectordata: vector property %q was not found", name)
	}
	return selected, nil
}

// FullTextProperty selects a full-text-indexed data property by record name.
// An empty name is valid only when exactly one such property exists.
// The returned property belongs to the model and must be treated as read-only.
func (m *CollectionModel) FullTextProperty(name string) (*DataPropertyModel, error) {
	var selected *DataPropertyModel
	if m != nil {
		for _, property := range m.Properties {
			if p, ok := property.(*DataPropertyModel); ok && p != nil && p.IsFullTextIndexed && (name == "" || p.Name == name) {
				if selected != nil {
					return nil, fmt.Errorf("vectordata: full-text property selection is ambiguous")
				}
				selected = p
			}
		}
	}
	if selected == nil {
		return nil, fmt.Errorf("vectordata: full-text property %q was not found", name)
	}
	return selected, nil
}
