func testSearchEmbeddingGenerator[E any](t *testing.T, output E, supported bool) {
	t.Helper()
	type record struct {
		ID     string    `vectordata:"key"`
		Vector []float32 `vectordata:"vector,dimensions=3"`
	}
	calls := 0
	generator := embedding.Bind(&bindingGenerator[string, E]{
		generate: func(_ context.Context, inputs []string, _ *embedding.Options) (*embedding.Generated[E], error) {
			calls++
			if len(inputs) != 1 || inputs[0] != "query" {
				t.Fatalf("query inputs = %v", inputs)
			}
			return &embedding.Generated[E]{Embeddings: []E{output}}, nil
		},
	})
	model, err := buildModel[string, record](&vectordata.Definition{EmbeddingGenerator: generator})
	if err != nil {
		t.Fatal(err)
	}
	vector, err := model.VectorProperty("")
	if err != nil || vector.EmbeddingGenerator != generator || vector.EmbeddingType != reflect.TypeFor[[]float32]() ||
		model.EmbeddingGenerationRequired || calls != 0 {
		t.Fatalf("search-only model = %+v, %v; calls = %d", model, err, calls)
	}
	if !supported {
		if vector.SearchEmbeddingGenerator != nil {
			t.Fatal("unsupported search output was selected")
		}
		type generatedRecord struct {
			ID     string `vectordata:"key"`
			Vector string `vectordata:"vector,dimensions=3"`
		}
		model, err = buildModel[string, generatedRecord](&vectordata.Definition{EmbeddingGenerator: generator})
		if err == nil || model != nil || !strings.Contains(err.Error(), "unsupported embedding type") || calls != 0 {
			t.Fatalf("unsupported generated output accepted: %+v, %v", model, err)
		}
		return
	}
	if vector.SearchEmbeddingGenerator != generator {
		t.Fatal("compatible search generator was not selected")
	}
	result, err := vector.SearchEmbeddingGenerator.Generate(t.Context(), []any{"query"}, nil)
	if err != nil || result == nil || len(result.Embeddings) != 1 || !reflect.DeepEqual(result.Embeddings[0], output) || calls != 1 {
		t.Fatalf("search generation = %+v, %v; calls = %d", result, err, calls)
	}
	if _, err := vector.SearchEmbeddingGenerator.Generate(t.Context(), []any{42}, nil); err == nil || calls != 1 {
		t.Fatalf("incompatible search input reached the generator: %v, calls = %d", err, calls)
	}
}

