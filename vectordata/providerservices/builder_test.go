func TestBuild_KeyAutoGeneration(t *testing.T) {
	for _, supported := range []bool{false, true} {
		for _, requested := range []*bool{nil, new(false), new(true)} {
			for _, dynamic := range []bool{false, true} {
				t.Run(fmt.Sprintf("supported=%t/requested=%v/dynamic=%t", supported, requested, dynamic), func(t *testing.T) {
					config := modelConfig()
					config.SupportsKeyAutoGeneration = func(typ reflect.Type) bool {
						if typ != reflect.TypeFor[string]() {
							t.Fatalf("auto-generation checked for unexpected type %v", typ)
						}
						return supported
					}
					input := &vectordata.KeyProperty{
						Name: "ID", Type: reflect.TypeFor[string](), IsAutoGenerated: requested,
					}
					options := &vectordata.Definition{
						Properties: []vectordata.Property{input},
					}
					var model *providerservices.CollectionModel
					var err error
					if dynamic {
						model, err = providerservices.Build(reflect.TypeFor[string](), reflect.TypeFor[map[string]any](), options, config)
					} else {
						model, err = providerservices.Build(reflect.TypeFor[string](), reflect.TypeFor[taggedRecord](), options, config)
					}
					if !supported && requested != nil && *requested {
						if err == nil || model != nil || !strings.Contains(err.Error(), "does not support auto-generation") {
							t.Fatalf("unsupported auto-generation accepted: %+v, %v", model, err)
						}
						return
					}
					if err != nil {
						t.Fatal(err)
					}
					want := supported
					if requested != nil {
						want = *requested
					}
					key := model.Properties[0].(*providerservices.KeyPropertyModel)
					if key.IsAutoGenerated != want || input.IsAutoGenerated != requested {
						t.Fatalf("auto-generation = %t; want %t, input = %+v", key.IsAutoGenerated, want, input)
					}
					key.IsAutoGenerated = !want
					if requested != nil && *requested != want {
						t.Fatal("model retained the caller's boolean pointer")
					}
				})
			}
		}
	}
	type record struct {
		ID string `vectordata:"key"`
	}
	for _, supported := range []bool{false, true} {
		config := modelConfig()
		config.SupportsKeyAutoGeneration = func(reflect.Type) bool { return supported }
		model, err := providerservices.Build(reflect.TypeFor[string](), reflect.TypeFor[record](), nil, config)
		if err != nil || model.Properties[0].(*providerservices.KeyPropertyModel).IsAutoGenerated != supported {
			t.Fatalf("tag default = %+v, %v; want %t", model, err, supported)
		}
	}
}

