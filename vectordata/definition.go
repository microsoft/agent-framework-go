package vectordata

import (
	"reflect"

	"github.com/microsoft/agent-framework-go/embedding"
)

// DistanceFunction identifies a vector comparison function. Built-in values use
// lowercase snake case. Providers may accept additional, case-sensitive values.
// An empty value uses the provider's default.
type DistanceFunction string

const (
	// CosineSimilarity compares vector angles, from -1 (opposite) to 1 (identical).
	CosineSimilarity DistanceFunction = "cosine_similarity"
	// CosineDistance is 1 minus cosine similarity; smaller values are nearer.
	CosineDistance DistanceFunction = "cosine_distance"
	// DotProductSimilarity compares vector lengths and angles; larger is nearer.
	DotProductSimilarity DistanceFunction = "dot_product_similarity"
	// NegativeDotProductSimilarity is negative dot product; smaller is nearer.
	NegativeDotProductSimilarity DistanceFunction = "negative_dot_product_similarity"
	// EuclideanDistance is the L2 distance.
	EuclideanDistance DistanceFunction = "euclidean_distance"
	// EuclideanSquaredDistance is the squared L2 distance.
	EuclideanSquaredDistance DistanceFunction = "euclidean_squared_distance"
	// HammingDistance counts differing coordinates.
	HammingDistance DistanceFunction = "hamming_distance"
	// ManhattanDistance is the sum of absolute coordinate differences.
	ManhattanDistance DistanceFunction = "manhattan_distance"
)

// IndexKind identifies a vector index. Built-in values use lowercase snake case.
// Providers may accept additional, case-sensitive values. An empty value uses
// the provider's default.
type IndexKind string

const (
	HNSW          IndexKind = "hnsw"
	Flat          IndexKind = "flat"
	IVFFlat       IndexKind = "ivf_flat"
	DiskANN       IndexKind = "disk_ann"
	QuantizedFlat IndexKind = "quantized_flat"
	Dynamic       IndexKind = "dynamic"
)

// Property describes a key, data, or vector field. Its implementations are
// *KeyProperty, *DataProperty, and *VectorProperty.
type Property interface {
	property()
}

// KeyProperty describes the unique record key. Type can be inferred from a
// struct field; dynamic records require it explicitly. A nil IsAutoGenerated
// leaves key generation to the provider's default, distinct from explicit false.
// StorageName defaults to Name unless the provider reserves a key storage name.
// ProviderAnnotations are provider-specific.
type KeyProperty struct {
	Name                string
	Type                reflect.Type
	StorageName         string
	ProviderAnnotations map[string]any
	IsAutoGenerated     *bool
}

// DataProperty describes a stored data field. Indexing and full-text indexing
// are disabled by default. Type can be inferred from a struct field.
type DataProperty struct {
	Name                string
	Type                reflect.Type
	StorageName         string
	ProviderAnnotations map[string]any
	IsIndexed           bool
	IsFullTextIndexed   bool
}

// VectorProperty describes a vector field or input for embedding generation.
// Dimensions must be positive. IndexKind and DistanceFunction default to the
// provider's choices. Type can be inferred from a struct field.
//
// EmbeddingGenerator overrides collection defaults; create it with
// [embedding.Bind]. For a field supported natively by the provider, an explicit
// EmbeddingType must match the field type. Its generator may still embed search
// queries. For other fields, EmbeddingType requests a supported generator output
// type; an explicit value must match the selected generator's declared output.
// The field must exactly match the generator's concrete input type or implement
// its input interface.
//
// Without a generator, an explicit EmbeddingType can describe the output of
// provider-managed embedding generation. Providers validate supported types
// and their representation-specific storage requirements.
type VectorProperty struct {
	Name                string
	Type                reflect.Type
	StorageName         string
	ProviderAnnotations map[string]any
	Dimensions          int
	IndexKind           IndexKind
	DistanceFunction    DistanceFunction
	EmbeddingGenerator  *embedding.BoundGenerator
	EmbeddingType       reflect.Type
}

// Definition configures the properties stored in a collection. Providers
// combine it with the record's vectordata tags when constructing a collection
// handle; they do not modify the caller's definition.
//
// Tags use a role followed by comma-separated settings:
//
//	ID     string    `vectordata:"key,autogenerated=false,storage=id"`
//	Text   string    `vectordata:"data,indexed,fulltext"`
//	Vector []float32 `vectordata:"vector,dimensions=1536,index=hnsw,distance=cosine_similarity"`
//
// Built-in index and distance names use lowercase snake case. Provider-specific
// values and storage names retain their casing. Explicit properties override
// tags, while empty storage, index, and distance names retain tag settings.
// Dynamic map[string]any records require explicit property types.
//
// A property generator takes precedence over EmbeddingGenerator, which takes
// precedence over CollectionOptions.EmbeddingGenerator.
type Definition struct {
	Properties         []Property
	EmbeddingGenerator *embedding.BoundGenerator
}

func (*KeyProperty) property()    {}
func (*DataProperty) property()   {}
func (*VectorProperty) property() {}
